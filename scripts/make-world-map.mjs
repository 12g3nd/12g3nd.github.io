// Draws the Travel page's world map, once, and commits it as data.
//
// The coastlines come from Natural Earth (public domain) by way of the
// world-atlas package's 1:110m TopoJSON, fetched from jsDelivr. They are
// decoded, projected with the same Equal Earth math the page uses for its dots
// (src/utils/equalEarth.ts, imported directly — Node strips the types), and
// written to src/data/worldMap.ts as one SVG path plus the fit that produced
// it. The page then needs no map library at all: it draws the path and
// projects each place through the same fit.
//
// Deliberately not part of `npm run build`, like fetch-fonts.mjs: the output is
// committed, so neither a build nor CI depends on jsDelivr being up. Re-run it
// only to change the map's detail, width, or what it leaves out:
//
//   node scripts/make-world-map.mjs

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { equalEarthRaw } from '../src/utils/equalEarth.ts';

const SOURCE = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json';
const OUT = path.resolve('src', 'data', 'worldMap.ts');

/** Map width in SVG units. Height follows from the projection's aspect. */
const WIDTH = 1000;
/** Antarctica (ISO 3166 numeric 010): a long white band of nothing visited. */
const SKIP = new Set(['010']);
const RAD = Math.PI / 180;

/** Decode TopoJSON's quantised, delta-encoded arcs into [lng, lat] lines. */
function decodeArcs(topo) {
  const [sx, sy] = topo.transform.scale;
  const [tx, ty] = topo.transform.translate;
  return topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

/** One ring from arc indices; a negative index (~i) means arc i reversed. */
function ring(arcs, indices) {
  const points = [];
  for (const i of indices) {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    // Consecutive arcs share their join point; keep it once.
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

/**
 * A few rings (Fiji, Russia's eastern tip) cross the antimeridian, so the
 * source jumps from +180 to -180 mid-ring. Projected as-is that draws a
 * stroke across the entire map. Unwrapping keeps each ring continuous: the
 * overhang lands just past the map's edge, where the view clips it.
 */
function unwrap(points) {
  let prev = null;
  return points.map(([lng, lat]) => {
    if (prev !== null) {
      while (lng - prev > 180) lng -= 360;
      while (lng - prev < -180) lng += 360;
    }
    prev = lng;
    return [lng, lat];
  });
}

function polygons(geometry) {
  if (geometry.type === 'Polygon') return [geometry.arcs];
  if (geometry.type === 'MultiPolygon') return geometry.arcs;
  return [];
}

async function main() {
  process.stdout.write('fetching world-atlas 110m ... ');
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch failed (${res.status})`);
  const topo = await res.json();
  console.log('ok');

  const arcs = decodeArcs(topo);
  const countries = topo.objects.countries.geometries.filter((g) => !SKIP.has(g.id));

  // Project every ring with the raw (unit) projection first, to find the
  // bounds the fit has to cover.
  const rings = [];
  for (const g of countries) {
    for (const poly of polygons(g)) {
      for (const r of poly) {
        rings.push(unwrap(ring(arcs, r)).map(([lng, lat]) => equalEarthRaw(lng * RAD, lat * RAD)));
      }
    }
  }
  // Width is the true ±180° span at the equator, so an unwrapped ring that
  // overhangs the edge does not widen the map; height is the land's own.
  const minX = equalEarthRaw(-Math.PI, 0)[0];
  const maxX = equalEarthRaw(Math.PI, 0)[0];
  let minY = Infinity, maxY = -Infinity;
  for (const r of rings) {
    for (const [, y] of r) {
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }

  const k = WIDTH / (maxX - minX);
  const height = Math.ceil((maxY - minY) * k);
  const fit = { k: +k.toFixed(4), tx: +(-minX * k).toFixed(4), ty: +(maxY * k).toFixed(4) };

  // One path for all land. One decimal is ~1/1000 of the map's width, finer
  // than the 110m source and enough to keep the file small.
  const r1 = (n) => Math.round(n * 10) / 10;
  const d = rings
    .map((r) => {
      const pts = r.map(([x, y]) => [r1(fit.tx + fit.k * x), r1(fit.ty - fit.k * y)]);
      return 'M' + pts.map(([x, y]) => `${x} ${y}`).join('L') + 'Z';
    })
    .join('');

  const file = `// GENERATED by scripts/make-world-map.mjs — do not edit by hand; re-run it.
//
// Land outlines from Natural Earth (public domain) via world-atlas 2.0.2,
// 1:110m, projected with Equal Earth (src/utils/equalEarth.ts). Antarctica is
// left out. \`fit\` is the scale/offset that placed the coastlines; project a
// place through the same fit and it lands on them.

import type { Fit } from '../utils/equalEarth';

export const WORLD_WIDTH = ${WIDTH};
export const WORLD_HEIGHT = ${height};
export const WORLD_FIT: Fit = ${JSON.stringify(fit)};
export const WORLD_LAND =
  '${d}';
`;
  await writeFile(OUT, file, 'utf8');
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${WIDTH}x${height}, ${(d.length / 1024).toFixed(1)} KB of path`);
}

await main();
